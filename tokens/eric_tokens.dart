ThemeData ericTheme({bool escuro = false}) {
  final c = escuro ? EricColors.escuro : EricColors.claro;
  return ThemeData(
    useMaterial3: true,
    brightness: escuro ? Brightness.dark : Brightness.light,
    fontFamily: 'Poppins',
    scaffoldBackgroundColor: c.page,
    colorScheme: ColorScheme.fromSeed(seedColor: c.primary, brightness: escuro ? Brightness.dark : Brightness.light).copyWith(primary: c.primary, onPrimary: c.onPrimary, surface: c.surface, error: c.badFg, outline: c.fieldBd),
    extensions: [c],
    cardTheme: CardThemeData(elevation: 0, color: c.surface, shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(EricRadius.mCard), side: BorderSide(color: c.border))),
    filledButtonTheme: FilledButtonThemeData(style: FilledButton.styleFrom(minimumSize: const Size.fromHeight(EricSize.mButton), backgroundColor: c.primary, foregroundColor: c.onPrimary, elevation: 0, shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(EricRadius.mField)), textStyle: const TextStyle(fontSize: 16, fontWeight: FontWeight.w600))),
    inputDecorationTheme: InputDecorationTheme(filled: true, fillColor: c.surface, contentPadding: const EdgeInsets.symmetric(horizontal: 14, vertical: 16), border: OutlineInputBorder(borderRadius: BorderRadius.circular(EricRadius.mField), borderSide: BorderSide(color: c.fieldBd)), enabledBorder: OutlineInputBorder(borderRadius: BorderRadius.circular(EricRadius.mField), borderSide: BorderSide(color: c.fieldBd)), focusedBorder: OutlineInputBorder(borderRadius: BorderRadius.circular(EricRadius.mField), borderSide: BorderSide(color: c.focus, width: 2)), errorBorder: OutlineInputBorder(borderRadius: BorderRadius.circular(EricRadius.mField), borderSide: BorderSide(color: c.badFg))),
    navigationBarTheme: NavigationBarThemeData(height: EricSize.mBottomNav, backgroundColor: c.surface, indicatorColor: c.soft, elevation: 0),
    appBarTheme: AppBarTheme(toolbarHeight: EricSize.mHeader, backgroundColor: c.surface, foregroundColor: c.text, elevation: 0, scrolledUnderElevation: 0),
    bottomSheetTheme: BottomSheetThemeData(backgroundColor: c.surface, elevation: 0, showDragHandle: true, shape: const RoundedRectangleBorder(borderRadius: BorderRadius.vertical(top: Radius.circular(EricRadius.mSheet)))),
  );
}
