-- id a partir do slug, com erro amigável listando as opções
CREATE FUNCTION _id_slug(p_tabela text, p_slug text) RETURNS bigint LANGUAGE plpgsql STABLE AS $$
DECLARE v bigint; v_opcoes text;
BEGIN
  EXECUTE format('SELECT id FROM %I WHERE slug = $1', p_tabela) INTO v USING p_slug;
  IF v IS NULL THEN
    EXECUTE format('SELECT string_agg(slug, '', '' ORDER BY id) FROM %I', p_tabela) INTO v_opcoes;
    RAISE EXCEPTION '"%" não existe em %. Opções: %', p_slug, p_tabela, v_opcoes;
  END IF;
  RETURN v;
END $$;

CREATE FUNCTION tem_permissao(p_user bigint, p_municipio bigint, p_permissao text)
RETURNS boolean LANGUAGE sql STABLE AS $$
  SELECT EXISTS (
    SELECT 1
    FROM vinculos v
    JOIN perfis pf           ON pf.id = v.perfil_id AND pf.ativo
    JOIN perfil_permissao pp ON pp.perfil_id = pf.id
    JOIN permissoes pe       ON pe.id = pp.permissao_id
    WHERE v.user_id = p_user
      AND v.municipio_id = p_municipio
      AND pe.slug = p_permissao
      AND v.inicio <= current_date
      AND (v.fim IS NULL OR v.fim >= current_date)
  )
$$;

CREATE FUNCTION esta_lotado(p_user bigint, p_setor bigint)
RETURNS boolean LANGUAGE sql STABLE AS $$
  SELECT EXISTS (
    SELECT 1 FROM vinculos v
    WHERE v.user_id = p_user AND v.setor_id = p_setor
      AND v.inicio <= current_date AND (v.fim IS NULL OR v.fim >= current_date)
  )
$$;

CREATE FUNCTION _exigir_permissao(p_user bigint, p_municipio bigint, p_permissao text)
RETURNS void LANGUAGE plpgsql AS $$
BEGIN
  IF NOT tem_permissao(p_user, p_municipio, p_permissao) THEN
    RAISE EXCEPTION 'Usuário % não tem a permissão "%" neste município.', p_user, p_permissao;
  END IF;
END $$;

-- Valores respondidos para "formulário X, chave Y" numa solicitação
-- (qualquer versão do formulário — é o que a chave estável garante)
CREATE FUNCTION valores_resposta(p_sol bigint, p_form bigint, p_chave text)
RETURNS text[] LANGUAGE sql STABLE AS $$
  SELECT COALESCE(array_agg(COALESCE(co.valor, r.valor))
                  FILTER (WHERE COALESCE(co.valor, r.valor) IS NOT NULL), '{}')
  FROM respostas r
  JOIN campos c              ON c.id = r.campo_id
  JOIN secoes s              ON s.id = c.secao_id
  JOIN formulario_versoes fv ON fv.id = s.formulario_versao_id
  LEFT JOIN resposta_opcoes ro ON ro.resposta_id = r.id
  LEFT JOIN campo_opcoes co    ON co.id = ro.campo_opcao_id
  WHERE r.solicitacao_id = p_sol AND fv.formulario_id = p_form AND c.chave = p_chave
$$;

CREATE FUNCTION avaliar_condicao(p_cond bigint, p_sol bigint)
RETURNS boolean LANGUAGE plpgsql STABLE AS $$
DECLARE c condicoes%ROWTYPE; op text; vals text[];
BEGIN
  SELECT * INTO c FROM condicoes WHERE id = p_cond;
  SELECT slug INTO op FROM operadores WHERE id = c.operador_id;
  vals := valores_resposta(p_sol, c.gatilho_formulario_id, c.gatilho_chave);
  RETURN COALESCE(CASE op
    WHEN 'igual'      THEN c.valor = ANY (vals)
    WHEN 'diferente'  THEN NOT (c.valor = ANY (vals))
    WHEN 'preenchido' THEN cardinality(vals) > 0
    WHEN 'vazio'      THEN cardinality(vals) = 0
    WHEN 'contem'     THEN EXISTS (SELECT 1 FROM unnest(vals) v WHERE v ILIKE '%' || c.valor || '%')
    WHEN 'maior'      THEN EXISTS (SELECT 1 FROM unnest(vals) v WHERE v ~ '^-?[0-9.]+$' AND v::numeric > c.valor::numeric)
    WHEN 'menor'      THEN EXISTS (SELECT 1 FROM unnest(vals) v WHERE v ~ '^-?[0-9.]+$' AND v::numeric < c.valor::numeric)
  END, false);
END $$;

CREATE FUNCTION avaliar_grupo(p_grupo bigint, p_sol bigint)
RETURNS boolean LANGUAGE plpgsql STABLE AS $$
DECLARE v_logica text; v_res boolean[];
BEGIN
  SELECT logica INTO v_logica FROM condicao_grupos WHERE id = p_grupo;
  SELECT array_agg(r) INTO v_res FROM (
    SELECT avaliar_condicao(c.id, p_sol) AS r FROM condicoes c WHERE c.grupo_id = p_grupo
    UNION ALL
    SELECT avaliar_grupo(g.id, p_sol) FROM condicao_grupos g WHERE g.parent_grupo_id = p_grupo
  ) x;
  IF v_res IS NULL THEN RETURN true; END IF;
  IF v_logica = 'E' THEN RETURN true = ALL (v_res); END IF;
  RETURN true = ANY (v_res);
END $$;

-- Campo visível = a seção é visível E o campo é visível
CREATE FUNCTION campo_visivel(p_campo bigint, p_sol bigint)
RETURNS boolean LANGUAGE sql STABLE AS $$
  SELECT
    COALESCE((SELECT avaliar_grupo(g.id, p_sol) FROM condicao_grupos g
              JOIN campos c ON c.secao_id = g.secao_id
              WHERE c.id = p_campo AND g.parent_grupo_id IS NULL), true)
    AND
    COALESCE((SELECT avaliar_grupo(g.id, p_sol) FROM condicao_grupos g
              WHERE g.campo_id = p_campo AND g.parent_grupo_id IS NULL), true)
$$;

-- Texto legível de um grupo de condições
CREATE FUNCTION descrever_grupo(p_grupo bigint)
RETURNS text LANGUAGE plpgsql STABLE AS $$
DECLARE v_logica text; v_txt text;
BEGIN
  SELECT logica INTO v_logica FROM condicao_grupos WHERE id = p_grupo;
  SELECT string_agg(t, ' ' || v_logica || ' ') INTO v_txt FROM (
    SELECT '[' || f.nome || '] ' || c.gatilho_chave || ' ' || o.slug
           || COALESCE(' "' || c.valor || '"', '') AS t
    FROM condicoes c
    JOIN operadores o  ON o.id = c.operador_id
    JOIN formularios f ON f.id = c.gatilho_formulario_id
    WHERE c.grupo_id = p_grupo
    UNION ALL
    SELECT '(' || descrever_grupo(g.id) || ')' FROM condicao_grupos g WHERE g.parent_grupo_id = p_grupo
  ) x;
  RETURN COALESCE(v_txt, '(sem condições)');
END $$;

-- Serviço × canal: sem canal marcado = sem restrição; com canal = restringe;
-- efetivo = interseção do serviço com todas as categorias acima dele
CREATE VIEW servicos_por_canal AS
WITH RECURSIVE cadeia AS (
  SELECT s.id AS servico_id, s.categoria_id FROM servicos s
  UNION ALL
  SELECT c.servico_id, cat.parent_id
  FROM cadeia c JOIN categorias cat ON cat.id = c.categoria_id
  WHERE cat.parent_id IS NOT NULL
)
SELECT s.id AS servico_id, s.municipio_id, s.nome AS servico, ca.id AS canal_id, ca.slug AS canal
FROM servicos s
CROSS JOIN canais ca
WHERE s.ativo AND ca.ativo
  AND (   NOT EXISTS (SELECT 1 FROM servico_canais sc WHERE sc.servico_id = s.id)
       OR EXISTS     (SELECT 1 FROM servico_canais sc WHERE sc.servico_id = s.id AND sc.canal_id = ca.id))
  AND NOT EXISTS (
    SELECT 1 FROM cadeia c
    WHERE c.servico_id = s.id
      AND EXISTS     (SELECT 1 FROM categoria_canais cc WHERE cc.categoria_id = c.categoria_id)
      AND NOT EXISTS (SELECT 1 FROM categoria_canais cc WHERE cc.categoria_id = c.categoria_id AND cc.canal_id = ca.id)
  );

-- Campos obrigatórios e visíveis ainda sem resposta (abertura + etapa atual)
CREATE FUNCTION faltando(p_sol bigint)
RETURNS TABLE (momento text, formulario text, chave text, pergunta text)
LANGUAGE sql STABLE AS $$
  SELECT CASE WHEN svf.etapa_id IS NULL THEN 'abertura' ELSE 'etapa' END,
         f.nome, c.chave, c.rotulo
  FROM solicitacoes sol
  JOIN servico_versao_formularios svf ON svf.servico_versao_id = sol.servico_versao_id
                                     AND (svf.etapa_id IS NULL OR svf.etapa_id = sol.etapa_atual_id)
  JOIN formulario_versoes fv ON fv.id = svf.formulario_versao_id
  JOIN formularios f         ON f.id = fv.formulario_id
  JOIN secoes s              ON s.formulario_versao_id = fv.id
  JOIN campos c              ON c.secao_id = s.id
  LEFT JOIN tramites t       ON t.solicitacao_id = sol.id AND t.etapa_id = svf.etapa_id AND t.saiu_em IS NULL
  WHERE sol.id = p_sol
    AND c.obrigatorio
    AND campo_visivel(c.id, sol.id)
    AND NOT EXISTS (SELECT 1 FROM respostas r
                    WHERE r.solicitacao_id = sol.id AND r.campo_id = c.id
                      AND r.tramite_id IS NOT DISTINCT FROM t.id)
  ORDER BY svf.etapa_id NULLS FIRST, s.ordem, c.ordem
$$;

