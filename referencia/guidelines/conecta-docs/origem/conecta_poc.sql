-- Estrutura do serviço na versão mais recente (rascunho, se houver)
CREATE FUNCTION ver_servico(p_servico bigint)
RETURNS TABLE (versao int, status text, etapa text, setor text, inicial boolean,
               notifica text, situacao text, leva_para text, formularios text)
LANGUAGE sql STABLE AS $$
  WITH v AS (SELECT * FROM servico_versoes WHERE servico_id = p_servico ORDER BY numero DESC LIMIT 1)
  SELECT v.numero, v.status, '(abertura)', NULL, NULL, NULL, NULL, NULL,
         string_agg(f.nome || ' v' || fv.numero, ', ' ORDER BY svf.ordem)
  FROM v
  JOIN servico_versao_formularios svf ON svf.servico_versao_id = v.id AND svf.etapa_id IS NULL
  JOIN formulario_versoes fv ON fv.id = svf.formulario_versao_id
  JOIN formularios f ON f.id = fv.formulario_id
  GROUP BY v.numero, v.status
  UNION ALL
  SELECT * FROM (
    SELECT v.numero, v.status, e.nome, st.nome, e.inicial,
           CASE WHEN e.notifica_solicitante THEN e.mensagem_notificacao END, si.nome,
           COALESCE((SELECT nome FROM etapas WHERE id = si.etapa_destino_id), CASE WHEN si.id IS NOT NULL THEN '(encerra)' END),
           (SELECT string_agg(f.nome || ' v' || fv.numero || CASE WHEN svf.visivel_cidadao THEN ' [visível ao cidadão]' ELSE '' END, ', ' ORDER BY svf.ordem)
            FROM servico_versao_formularios svf
            JOIN formulario_versoes fv ON fv.id = svf.formulario_versao_id
            JOIN formularios f ON f.id = fv.formulario_id
            WHERE svf.etapa_id = e.id)
    FROM v
    JOIN etapas e   ON e.servico_versao_id = v.id
    JOIN setores st ON st.id = e.setor_id
    LEFT JOIN situacoes si ON si.etapa_origem_id = e.id
    ORDER BY e.inicial DESC, e.id, si.id
  ) x
$$;

-- Estrutura do formulário na versão mais recente (rascunho, se houver)
CREATE FUNCTION ver_formulario(p_form bigint)
RETURNS TABLE (versao int, status text, secao text, chave text, tipo text, pergunta text,
               obrigatorio boolean, opcoes text, validacoes text, aparece_se text)
LANGUAGE sql STABLE AS $$
  WITH v AS (SELECT * FROM formulario_versoes WHERE formulario_id = p_form ORDER BY numero DESC LIMIT 1)
  SELECT v.numero, v.status, s.titulo, c.chave, tc.slug, c.rotulo, c.obrigatorio,
         (SELECT string_agg(valor, ', ' ORDER BY ordem) FROM campo_opcoes WHERE campo_id = c.id),
         (SELECT string_agg(tv.slug || '=' || cv.valor, ', ') FROM campo_validacoes cv
          JOIN tipos_validacao tv ON tv.id = cv.tipo_validacao_id WHERE cv.campo_id = c.id),
         NULLIF(concat_ws(' | ',
           (SELECT 'seção: ' || descrever_grupo(g.id) FROM condicao_grupos g WHERE g.secao_id = s.id AND g.parent_grupo_id IS NULL),
           (SELECT descrever_grupo(g.id) FROM condicao_grupos g WHERE g.campo_id = c.id AND g.parent_grupo_id IS NULL)), '')
  FROM v
  JOIN secoes s ON s.formulario_versao_id = v.id
  LEFT JOIN campos c ON c.secao_id = s.id
  LEFT JOIN tipos_campo tc ON tc.id = c.tipo_campo_id
  ORDER BY s.ordem, c.ordem
$$;

-- Timeline pública: etapa, setor e situação (rótulo público ou nome)
CREATE FUNCTION timeline(p_sol bigint)
RETURNS TABLE (quando text, etapa text, setor text, situacao text)
LANGUAGE sql STABLE AS $$
  SELECT to_char(t.entrou_em, 'DD/MM HH24:MI:SS'),
         COALESCE(e.rotulo_publico, e.nome),
         st.nome,
         COALESCE(si.rotulo_publico, si.nome, '(em andamento)')
  FROM tramites t
  JOIN etapas e   ON e.id = t.etapa_id
  JOIN setores st ON st.id = e.setor_id
  LEFT JOIN situacoes si ON si.id = t.situacao_id
  WHERE t.solicitacao_id = p_sol
  ORDER BY t.entrou_em, t.id
$$;

-- Respostas da solicitação. p_cidadao = true mostra só o que o cidadão vê.
CREATE FUNCTION ver_respostas(p_sol bigint, p_cidadao boolean DEFAULT false)
RETURNS TABLE (momento text, formulario text, secao text, chave text, pergunta text,
               obrigatorio boolean, visivel boolean, resposta text)
LANGUAGE sql STABLE AS $$
  SELECT COALESCE(e.nome, 'abertura'), f.nome, s.titulo, c.chave, c.rotulo, c.obrigatorio,
         campo_visivel(c.id, sol.id),
         COALESCE(
           (SELECT string_agg(co.rotulo, ', ') FROM resposta_opcoes ro JOIN campo_opcoes co ON co.id = ro.campo_opcao_id WHERE ro.resposta_id = r.id),
           (SELECT string_agg(ra.nome_original, ', ') FROM resposta_arquivos ra WHERE ra.resposta_id = r.id),
           r.valor)
  FROM solicitacoes sol
  JOIN servico_versao_formularios svf ON svf.servico_versao_id = sol.servico_versao_id
  JOIN formulario_versoes fv ON fv.id = svf.formulario_versao_id
  JOIN formularios f ON f.id = fv.formulario_id
  JOIN secoes s ON s.formulario_versao_id = fv.id
  JOIN campos c ON c.secao_id = s.id
  LEFT JOIN etapas e ON e.id = svf.etapa_id
  LEFT JOIN respostas r ON r.solicitacao_id = sol.id AND r.campo_id = c.id
  WHERE sol.id = p_sol
    AND (NOT p_cidadao OR ((svf.etapa_id IS NULL OR svf.visivel_cidadao) AND r.id IS NOT NULL))
  ORDER BY svf.etapa_id NULLS FIRST, svf.ordem, s.ordem, c.ordem
$$;

-- Notificações recebidas por uma pessoa (pelo CPF) e por onde chegaram
CREATE FUNCTION notificacoes_da_pessoa(p_cpf text)
RETURNS TABLE (quando text, protocolo text, mensagem text, canais text)
LANGUAGE sql STABLE AS $$
  SELECT to_char(n.created_at, 'DD/MM HH24:MI:SS'), sol.numero_protocolo, n.mensagem,
         COALESCE((SELECT string_agg(cn.nome || COALESCE(' (' || ne.destino || ')', ''), ', ')
                   FROM notificacao_envios ne JOIN canais_notificacao cn ON cn.id = ne.canal_notificacao_id
                   WHERE ne.notificacao_id = n.id), 'nenhum canal disponível')
  FROM notificacoes n
  JOIN pessoas p ON p.id = n.pessoa_id
  JOIN solicitacoes sol ON sol.id = n.solicitacao_id
  WHERE p.cpf = p_cpf
  ORDER BY n.created_at, n.id
$$;

-- O que o usuário pode fazer agora na solicitação
CREATE FUNCTION situacoes_disponiveis(p_sol bigint)
RETURNS TABLE (etapa_atual text, setor text, situacao text, leva_para text)
LANGUAGE sql STABLE AS $$
  SELECT e.nome, st.nome, si.nome, COALESCE(d.nome, '(encerra)')
  FROM solicitacoes sol
  JOIN etapas e   ON e.id = sol.etapa_atual_id
  JOIN setores st ON st.id = e.setor_id
  JOIN situacoes si ON si.etapa_origem_id = e.id
  LEFT JOIN etapas d ON d.id = si.etapa_destino_id
  WHERE sol.id = p_sol
  ORDER BY si.id
$$;

-- Fila do usuário: solicitações paradas em etapas dos setores onde ele está lotado
CREATE FUNCTION fila(p_user bigint)
RETURNS TABLE (solicitacao bigint, protocolo text, servico text, etapa text, desde text, solicitante text, canal text)
LANGUAGE sql STABLE AS $$
  SELECT sol.id, sol.numero_protocolo, sv.nome, e.nome, to_char(t.entrou_em, 'DD/MM HH24:MI'), p.nome, ca.slug
  FROM vinculos v
  JOIN etapas e ON e.setor_id = v.setor_id
  JOIN solicitacoes sol ON sol.etapa_atual_id = e.id
  JOIN tramites t ON t.solicitacao_id = sol.id AND t.saiu_em IS NULL
  JOIN servico_versoes svv ON svv.id = sol.servico_versao_id
  JOIN servicos sv ON sv.id = svv.servico_id
  JOIN pessoas p ON p.id = sol.solicitante_pessoa_id
  JOIN canais ca ON ca.id = sol.canal_id
  WHERE v.user_id = p_user AND v.inicio <= current_date AND (v.fim IS NULL OR v.fim >= current_date)
  ORDER BY t.entrou_em
$$;

-- Lista de solicitações com situação atual
CREATE VIEW solicitacoes_resumo AS
