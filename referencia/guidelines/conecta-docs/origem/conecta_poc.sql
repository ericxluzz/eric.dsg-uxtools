CREATE FUNCTION criar_servico(p_user bigint, p_categoria bigint, p_nome text, p_conteudo_publico text DEFAULT NULL)
RETURNS bigint LANGUAGE plpgsql AS $$
DECLARE v_mun bigint; v_serv bigint;
BEGIN
  SELECT municipio_id INTO v_mun FROM categorias WHERE id = p_categoria;
  IF v_mun IS NULL THEN RAISE EXCEPTION 'Categoria % não existe.', p_categoria; END IF;
  PERFORM _exigir_permissao(p_user, v_mun, 'gerenciar_servicos');
  INSERT INTO servicos (municipio_id, categoria_id, nome, conteudo_publico)
  VALUES (v_mun, p_categoria, p_nome, p_conteudo_publico) RETURNING id INTO v_serv;
  INSERT INTO servico_versoes (servico_id, numero, status) VALUES (v_serv, 1, 'rascunho');
  RETURN v_serv;
END $$;

-- Copia etapas, situações e formulários vinculados de uma versão para outra
CREATE FUNCTION _copiar_servico_versao(p_origem bigint, p_destino bigint) RETURNS void LANGUAGE plpgsql AS $$
DECLARE me jsonb := '{}'; r record; v bigint;
BEGIN
  FOR r IN SELECT * FROM etapas WHERE servico_versao_id = p_origem ORDER BY id LOOP
    INSERT INTO etapas (servico_versao_id, setor_id, nome, rotulo_publico, inicial, final,
                        notifica_solicitante, mensagem_notificacao)
    VALUES (p_destino, r.setor_id, r.nome, r.rotulo_publico, r.inicial, r.final,
            r.notifica_solicitante, r.mensagem_notificacao) RETURNING id INTO v;
    me := me || jsonb_build_object(r.id::text, v);
  END LOOP;

  INSERT INTO situacoes (etapa_origem_id, etapa_destino_id, nome, rotulo_publico)
  SELECT (me ->> s.etapa_origem_id::text)::bigint, (me ->> s.etapa_destino_id::text)::bigint, s.nome, s.rotulo_publico
  FROM situacoes s JOIN etapas e ON e.id = s.etapa_origem_id
  WHERE e.servico_versao_id = p_origem ORDER BY s.id;

  INSERT INTO servico_versao_formularios (servico_versao_id, etapa_id, formulario_versao_id, ordem, visivel_cidadao)
  SELECT p_destino, (me ->> svf.etapa_id::text)::bigint, svf.formulario_versao_id, svf.ordem, svf.visivel_cidadao
  FROM servico_versao_formularios svf WHERE svf.servico_versao_id = p_origem;
END $$;

CREATE FUNCTION servico_em_edicao(p_servico bigint) RETURNS bigint LANGUAGE plpgsql AS $$
DECLARE v bigint; v_atual bigint;
BEGIN
  SELECT id INTO v FROM servico_versoes WHERE servico_id = p_servico AND status = 'rascunho';
  IF v IS NOT NULL THEN RETURN v; END IF;

  SELECT versao_atual_id INTO v_atual FROM servicos WHERE id = p_servico;
  IF v_atual IS NULL THEN RAISE EXCEPTION 'Serviço % não existe.', p_servico; END IF;

  INSERT INTO servico_versoes (servico_id, numero, status)
  VALUES (p_servico, (SELECT max(numero) + 1 FROM servico_versoes WHERE servico_id = p_servico), 'rascunho')
  RETURNING id INTO v;
  PERFORM _copiar_servico_versao(v_atual, v);
  RAISE NOTICE 'Rascunho novo do serviço % criado a partir da versão publicada.', p_servico;
  RETURN v;
END $$;

CREATE FUNCTION _etapa_em_edicao(p_servico bigint, p_nome text) RETURNS bigint LANGUAGE plpgsql AS $$
DECLARE v bigint; v_versao bigint := servico_em_edicao(p_servico);
BEGIN
  SELECT id INTO v FROM etapas WHERE servico_versao_id = v_versao AND nome = p_nome;
  IF v IS NULL THEN
    RAISE EXCEPTION 'Etapa "%" não existe no serviço %. Etapas: %', p_nome, p_servico,
      (SELECT string_agg(nome, ', ' ORDER BY id) FROM etapas WHERE servico_versao_id = v_versao);
  END IF;
  RETURN v;
END $$;

-- p_notificar: ao escolher uma situação nesta etapa, avisa o solicitante com p_mensagem
-- (marcadores {protocolo} {servico} {etapa} {situacao})
CREATE FUNCTION adicionar_etapa(p_servico bigint, p_setor bigint, p_nome text,
                                p_rotulo_publico text DEFAULT NULL, p_inicial boolean DEFAULT false,
                                p_notificar boolean DEFAULT false, p_mensagem text DEFAULT NULL)
RETURNS bigint LANGUAGE plpgsql AS $$
DECLARE v_versao bigint := servico_em_edicao(p_servico); v bigint;
BEGIN
  IF NOT EXISTS (SELECT 1 FROM setores st JOIN servicos s ON s.municipio_id = st.municipio_id
                 WHERE st.id = p_setor AND s.id = p_servico) THEN
    RAISE EXCEPTION 'Setor % não pertence ao município do serviço.', p_setor;
  END IF;
  IF EXISTS (SELECT 1 FROM etapas WHERE servico_versao_id = v_versao AND nome = p_nome) THEN
    RAISE EXCEPTION 'Já existe a etapa "%" neste serviço.', p_nome;
  END IF;
  IF p_inicial AND EXISTS (SELECT 1 FROM etapas WHERE servico_versao_id = v_versao AND inicial) THEN
    RAISE EXCEPTION 'O serviço já tem etapa inicial.';
  END IF;
  IF p_notificar AND COALESCE(btrim(p_mensagem), '') = '' THEN
    RAISE EXCEPTION 'Para notificar o solicitante, escreva a mensagem da etapa.';
  END IF;
  INSERT INTO etapas (servico_versao_id, setor_id, nome, rotulo_publico, inicial, notifica_solicitante, mensagem_notificacao)
  VALUES (v_versao, p_setor, p_nome, p_rotulo_publico, p_inicial, p_notificar, NULLIF(btrim(p_mensagem), ''))
  RETURNING id INTO v;
  RETURN v;
END $$;

-- Situação: escolhida na etapa de origem; leva à etapa de destino (NULL = encerra)
CREATE FUNCTION adicionar_situacao(p_servico bigint, p_etapa_origem text, p_etapa_destino text,
                                   p_nome text, p_rotulo_publico text DEFAULT NULL)
RETURNS bigint LANGUAGE plpgsql AS $$
DECLARE v_origem bigint := _etapa_em_edicao(p_servico, p_etapa_origem); v_destino bigint; v bigint;
BEGIN
  IF p_etapa_destino IS NOT NULL THEN v_destino := _etapa_em_edicao(p_servico, p_etapa_destino); END IF;
  IF EXISTS (SELECT 1 FROM situacoes WHERE etapa_origem_id = v_origem AND nome = p_nome) THEN
    RAISE EXCEPTION 'A etapa "%" já tem a situação "%".', p_etapa_origem, p_nome;
  END IF;
  INSERT INTO situacoes (etapa_origem_id, etapa_destino_id, nome, rotulo_publico)
  VALUES (v_origem, v_destino, p_nome, p_rotulo_publico) RETURNING id INTO v;
  RETURN v;
END $$;

-- Liga um formulário (versão publicada atual) à abertura (p_etapa NULL) ou a uma etapa
CREATE FUNCTION vincular_formulario(p_servico bigint, p_form bigint, p_etapa text DEFAULT NULL,
                                    p_visivel_cidadao boolean DEFAULT false)
RETURNS bigint LANGUAGE plpgsql AS $$
DECLARE v_versao bigint := servico_em_edicao(p_servico); v_etapa bigint; v_fv bigint; v bigint;
BEGIN
  IF p_etapa IS NOT NULL THEN v_etapa := _etapa_em_edicao(p_servico, p_etapa); END IF;

  SELECT f.versao_atual_id INTO v_fv FROM formularios f JOIN servicos s ON s.municipio_id = f.municipio_id
  WHERE f.id = p_form AND s.id = p_servico;
  IF v_fv IS NULL THEN
    RAISE EXCEPTION 'Formulário % não existe neste município ou ainda não foi publicado.', p_form;
  END IF;
  IF EXISTS (SELECT 1 FROM servico_versao_formularios svf JOIN formulario_versoes fv ON fv.id = svf.formulario_versao_id
             WHERE svf.servico_versao_id = v_versao AND svf.etapa_id IS NOT DISTINCT FROM v_etapa AND fv.formulario_id = p_form) THEN
    RAISE EXCEPTION 'Esse formulário já está vinculado aí.';
  END IF;

  INSERT INTO servico_versao_formularios (servico_versao_id, etapa_id, formulario_versao_id, ordem, visivel_cidadao)
  VALUES (v_versao, v_etapa, v_fv,
          COALESCE((SELECT max(ordem) FROM servico_versao_formularios
                    WHERE servico_versao_id = v_versao AND etapa_id IS NOT DISTINCT FROM v_etapa), 0) + 1,
          p_visivel_cidadao)
  RETURNING id INTO v;
  RETURN v;
END $$;

CREATE FUNCTION publicar_servico(p_user bigint, p_servico bigint) RETURNS text LANGUAGE plpgsql AS $$
DECLARE v_mun bigint; v_novo bigint; v_antigo bigint; v_num int; r record;
BEGIN
  SELECT municipio_id, versao_atual_id INTO v_mun, v_antigo FROM servicos WHERE id = p_servico;
  PERFORM _exigir_permissao(p_user, v_mun, 'gerenciar_servicos');

  SELECT id, numero INTO v_novo, v_num FROM servico_versoes WHERE servico_id = p_servico AND status = 'rascunho';
  IF v_novo IS NULL THEN RAISE EXCEPTION 'O serviço % não tem rascunho para publicar.', p_servico; END IF;

  IF (SELECT count(*) FROM etapas WHERE servico_versao_id = v_novo AND inicial) <> 1 THEN
    RAISE EXCEPTION 'O serviço precisa de exatamente uma etapa inicial.';
  END IF;
  FOR r IN SELECT e.nome FROM etapas e
           WHERE e.servico_versao_id = v_novo
             AND NOT EXISTS (SELECT 1 FROM situacoes s WHERE s.etapa_origem_id = e.id) LOOP
    RAISE EXCEPTION 'A etapa "%" não tem nenhuma situação: a solicitação ficaria presa nela.', r.nome;
  END LOOP;

  UPDATE servico_versoes SET status = 'substituida' WHERE id = v_antigo;
  UPDATE servico_versoes SET status = 'publicada', publicada_em = clock_timestamp() WHERE id = v_novo;
  UPDATE servicos SET versao_atual_id = v_novo WHERE id = p_servico;
  RETURN format('Serviço %s publicado na versão %s.', p_servico, v_num);
END $$;

-- Publica o formulário e faz os serviços que o usam adotarem a versão nova
CREATE FUNCTION publicar_formulario(p_user bigint, p_form bigint) RETURNS text LANGUAGE plpgsql AS $$
DECLARE v_mun bigint; v_novo bigint; v_antigo bigint; v_num int; r record; v_sv bigint; v_msg text;
BEGIN
  SELECT municipio_id, versao_atual_id INTO v_mun, v_antigo FROM formularios WHERE id = p_form;
  PERFORM _exigir_permissao(p_user, v_mun, 'gerenciar_formularios');

  SELECT id, numero INTO v_novo, v_num FROM formulario_versoes WHERE formulario_id = p_form AND status = 'rascunho';
  IF v_novo IS NULL THEN RAISE EXCEPTION 'O formulário % não tem rascunho para publicar.', p_form; END IF;
  IF NOT EXISTS (SELECT 1 FROM campos c JOIN secoes s ON s.id = c.secao_id WHERE s.formulario_versao_id = v_novo) THEN
    RAISE EXCEPTION 'O formulário não tem nenhum campo.';
  END IF;

  UPDATE formulario_versoes SET status = 'substituida' WHERE id = v_antigo;
  UPDATE formulario_versoes SET status = 'publicada', publicada_em = clock_timestamp() WHERE id = v_novo;
  UPDATE formularios SET versao_atual_id = v_novo WHERE id = p_form;
  v_msg := format('Formulário %s publicado na versão %s.', p_form, v_num);

  IF v_antigo IS NOT NULL THEN
    -- rascunhos de serviço passam a apontar para a versão nova
    UPDATE servico_versao_formularios svf SET formulario_versao_id = v_novo
    FROM servico_versoes sv
    WHERE sv.id = svf.servico_versao_id AND sv.status = 'rascunho' AND svf.formulario_versao_id = v_antigo;

    -- serviços publicados que usam a versão antiga ganham versão nova automaticamente
    FOR r IN SELECT DISTINCT s.id, s.versao_atual_id FROM servicos s
             JOIN servico_versao_formularios svf ON svf.servico_versao_id = s.versao_atual_id
             WHERE svf.formulario_versao_id = v_antigo
    LOOP
      INSERT INTO servico_versoes (servico_id, numero, status, publicada_em)
      VALUES (r.id, (SELECT max(numero) + 1 FROM servico_versoes WHERE servico_id = r.id), 'publicada', clock_timestamp())
      RETURNING id INTO v_sv;
      PERFORM _copiar_servico_versao(r.versao_atual_id, v_sv);
      UPDATE servico_versao_formularios SET formulario_versao_id = v_novo
      WHERE servico_versao_id = v_sv AND formulario_versao_id = v_antigo;
      UPDATE servico_versoes SET status = 'substituida' WHERE id = r.versao_atual_id;
      UPDATE servicos SET versao_atual_id = v_sv WHERE id = r.id;
      v_msg := v_msg || format(' Serviço %s passou para a versão %s.', r.id,
                               (SELECT numero FROM servico_versoes WHERE id = v_sv));
    END LOOP;
  END IF;
  RETURN v_msg;
END $$;

-- ---------------------------------------------------------------------
-- 4.5 Solicitações
-- ---------------------------------------------------------------------

CREATE FUNCTION abrir_solicitacao(p_user bigint, p_cpf_solicitante text, p_servico bigint, p_canal text,
                                  p_localidade bigint, p_logradouro text, p_descricao text,
                                  p_referencia text DEFAULT NULL)
RETURNS bigint LANGUAGE plpgsql AS $$
DECLARE
  v_mun bigint; v_versao bigint; v_canal bigint := _id_slug('canais', p_canal);
  v_solicitante bigint; v_pessoa_user bigint; v_inicial bigint;
  v_end bigint; v_sol bigint; v_protocolo text;
BEGIN
  SELECT municipio_id, versao_atual_id INTO v_mun, v_versao FROM servicos WHERE id = p_servico AND ativo;
  IF v_mun IS NULL THEN RAISE EXCEPTION 'Serviço % não existe ou está inativo.', p_servico; END IF;
  IF v_versao IS NULL THEN RAISE EXCEPTION 'O serviço % ainda não foi publicado.', p_servico; END IF;

  SELECT id INTO v_solicitante FROM pessoas WHERE cpf = p_cpf_solicitante;
  IF v_solicitante IS NULL THEN RAISE EXCEPTION 'Nenhuma pessoa com CPF %. Cadastre com criar_pessoa().', p_cpf_solicitante; END IF;

  SELECT pessoa_id INTO v_pessoa_user FROM users WHERE id = p_user;
  IF v_pessoa_user IS DISTINCT FROM v_solicitante THEN
    PERFORM _exigir_permissao(p_user, v_mun, 'abrir_para_terceiros');
  END IF;

  IF NOT EXISTS (SELECT 1 FROM servicos_por_canal WHERE servico_id = p_servico AND canal_id = v_canal) THEN
    RAISE EXCEPTION 'O serviço % não está disponível no canal "%". Disponível em: %', p_servico, p_canal,
      COALESCE((SELECT string_agg(canal, ', ') FROM servicos_por_canal WHERE servico_id = p_servico), 'nenhum canal');
  END IF;

  IF NOT EXISTS (SELECT 1 FROM localidades WHERE id = p_localidade AND municipio_id = v_mun) THEN
    RAISE EXCEPTION 'Localidade % não pertence ao município do serviço.', p_localidade;
  END IF;

  SELECT id INTO v_inicial FROM etapas WHERE servico_versao_id = v_versao AND inicial;

  INSERT INTO enderecos (municipio_id, localidade_id, logradouro, referencia)
  VALUES (v_mun, p_localidade, p_logradouro, p_referencia) RETURNING id INTO v_end;

  v_protocolo := upper(left(regexp_replace((SELECT nome FROM municipios WHERE id = v_mun), '[^A-Za-z]', '', 'g'), 3))
                 || '-' || extract(year FROM current_date)::text || '-'
                 || lpad(((SELECT count(*) FROM solicitacoes WHERE municipio_id = v_mun) + 1)::text, 6, '0');

  INSERT INTO solicitacoes (municipio_id, numero_protocolo, solicitante_pessoa_id, aberta_por_user_id,
                            canal_id, servico_versao_id, etapa_atual_id, endereco_id, descricao)
  VALUES (v_mun, v_protocolo, v_solicitante, p_user, v_canal, v_versao, v_inicial, v_end, p_descricao)
  RETURNING id INTO v_sol;

  INSERT INTO tramites (solicitacao_id, etapa_id, entrou_em) VALUES (v_sol, v_inicial, clock_timestamp());

  RAISE NOTICE 'Solicitação % aberta (protocolo %).', v_sol, v_protocolo;
  RETURN v_sol;
END $$;

-- regex a partir de máscara: # = dígito, demais caracteres literais
CREATE FUNCTION _mascara_regex(p_mascara text) RETURNS text LANGUAGE sql IMMUTABLE AS $$
  SELECT '^' || replace(regexp_replace(p_mascara, '([^#A-Za-z0-9])', '\\\1', 'g'), '#', '[0-9]') || '$'
$$;

CREATE FUNCTION _data(p text) RETURNS date LANGUAGE sql STABLE AS $$
  SELECT CASE WHEN p = 'hoje' THEN current_date ELSE p::date END
$$;

-- Grava a resposta de um campo validando tipo, visibilidade e validações.
-- p_valor: texto/número/data = o valor; seleção = valor da opção;
--          múltipla escolha e arquivos = itens separados por vírgula.
-- Valor vazio apaga a resposta.
CREATE FUNCTION _gravar_resposta(p_sol bigint, p_campo bigint, p_tramite bigint, p_valor text)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE
  v_tipo text; v_chave text; v_resp bigint; v_itens text[]; v_item text; v_opc bigint; v_val record; v_exts text[];
BEGIN
  SELECT tc.slug, c.chave INTO v_tipo, v_chave FROM campos c JOIN tipos_campo tc ON tc.id = c.tipo_campo_id WHERE c.id = p_campo;

  IF NOT campo_visivel(p_campo, p_sol) THEN
    RAISE EXCEPTION 'O campo "%" está oculto pelas condições e não pode ser respondido.', v_chave;
  END IF;

  DELETE FROM resposta_opcoes   WHERE resposta_id IN (SELECT id FROM respostas WHERE solicitacao_id = p_sol AND campo_id = p_campo AND tramite_id IS NOT DISTINCT FROM p_tramite);
  DELETE FROM resposta_arquivos WHERE resposta_id IN (SELECT id FROM respostas WHERE solicitacao_id = p_sol AND campo_id = p_campo AND tramite_id IS NOT DISTINCT FROM p_tramite);
  DELETE FROM respostas WHERE solicitacao_id = p_sol AND campo_id = p_campo AND tramite_id IS NOT DISTINCT FROM p_tramite;

  IF p_valor IS NULL OR btrim(p_valor) = '' THEN RETURN; END IF;

  v_itens := ARRAY(SELECT btrim(x) FROM unnest(string_to_array(p_valor, ',')) x WHERE btrim(x) <> '');

  -- tipo
  IF v_tipo = 'numero' AND p_valor !~ '^-?[0-9]+([.,][0-9]+)?$' THEN
    RAISE EXCEPTION 'O campo "%" espera um número.', v_chave;
  ELSIF v_tipo = 'data' THEN
    BEGIN PERFORM p_valor::date;
    EXCEPTION WHEN others THEN RAISE EXCEPTION 'O campo "%" espera uma data (AAAA-MM-DD).', v_chave; END;
  ELSIF v_tipo = 'selecao' AND cardinality(v_itens) > 1 THEN
    RAISE EXCEPTION 'O campo "%" é de seleção única.', v_chave;
  END IF;

  -- validações configuradas
  FOR v_val IN SELECT tv.slug, cv.valor FROM campo_validacoes cv JOIN tipos_validacao tv ON tv.id = cv.tipo_validacao_id
               WHERE cv.campo_id = p_campo AND tv.slug <> 'extensao' LOOP
    CASE v_val.slug
      WHEN 'tamanho_min' THEN
        IF length(p_valor) < v_val.valor::int THEN RAISE EXCEPTION '"%": mínimo de % caracteres.', v_chave, v_val.valor; END IF;
      WHEN 'tamanho_max' THEN
        IF length(p_valor) > v_val.valor::int THEN RAISE EXCEPTION '"%": máximo de % caracteres.', v_chave, v_val.valor; END IF;
      WHEN 'mascara' THEN
        IF p_valor !~ _mascara_regex(v_val.valor) THEN RAISE EXCEPTION '"%": formato esperado %.', v_chave, v_val.valor; END IF;
      WHEN 'data_min' THEN
        IF p_valor::date < _data(v_val.valor) THEN RAISE EXCEPTION '"%": data mínima %.', v_chave, v_val.valor; END IF;
      WHEN 'data_max' THEN
        IF p_valor::date > _data(v_val.valor) THEN RAISE EXCEPTION '"%": data máxima %.', v_chave, v_val.valor; END IF;
      WHEN 'quantidade_min' THEN
        IF cardinality(v_itens) < v_val.valor::int THEN RAISE EXCEPTION '"%": envie pelo menos % item(ns).', v_chave, v_val.valor; END IF;
      WHEN 'quantidade_max' THEN
        IF cardinality(v_itens) > v_val.valor::int THEN RAISE EXCEPTION '"%": no máximo % item(ns).', v_chave, v_val.valor; END IF;
      ELSE NULL;  -- tamanho_arquivo_max: não simulado (arquivos são só nomes)
    END CASE;
  END LOOP;

  v_exts := ARRAY(SELECT lower(cv.valor) FROM campo_validacoes cv JOIN tipos_validacao tv ON tv.id = cv.tipo_validacao_id
                  WHERE cv.campo_id = p_campo AND tv.slug = 'extensao');

  INSERT INTO respostas (solicitacao_id, campo_id, tramite_id, valor)
  VALUES (p_sol, p_campo, p_tramite,
          CASE WHEN v_tipo IN ('texto', 'texto_longo', 'numero', 'data') THEN p_valor END)
  RETURNING id INTO v_resp;

  IF v_tipo IN ('selecao', 'multipla_escolha') THEN
    FOREACH v_item IN ARRAY v_itens LOOP
      SELECT id INTO v_opc FROM campo_opcoes WHERE campo_id = p_campo AND valor = v_item;
      IF v_opc IS NULL THEN
        RAISE EXCEPTION '"%": opção "%" não existe. Opções: %', v_chave, v_item,
          (SELECT string_agg(valor, ', ' ORDER BY ordem) FROM campo_opcoes WHERE campo_id = p_campo);
      END IF;
      INSERT INTO resposta_opcoes VALUES (v_resp, v_opc);
    END LOOP;
  ELSIF v_tipo IN ('foto', 'video', 'arquivo') THEN
    FOREACH v_item IN ARRAY v_itens LOOP
      IF cardinality(v_exts) > 0
         AND NOT (COALESCE(lower(substring(v_item FROM '\.([^.]+)$')), '') = ANY (v_exts)) THEN
        RAISE EXCEPTION '"%": arquivo "%" com extensão não permitida. Permitidas: %', v_chave, v_item, array_to_string(v_exts, ', ');
      END IF;
      INSERT INTO resposta_arquivos (resposta_id, disk, path, nome_original, mime, tamanho_bytes, sha256)
      VALUES (v_resp, 'private', 'solicitacoes/' || p_sol || '/' || v_item, v_item,
              'application/octet-stream', 0, md5(v_item) || md5(reverse(v_item)));
    END LOOP;
  END IF;
END $$;

-- Acha o campo pela chave entre os formulários de um momento (abertura ou etapa)
CREATE FUNCTION _campo_da_solicitacao(p_sol bigint, p_etapa bigint, p_chave text, p_form bigint)
RETURNS bigint LANGUAGE plpgsql STABLE AS $$
DECLARE v_ids bigint[];
BEGIN
  SELECT array_agg(c.id) INTO v_ids
  FROM solicitacoes sol
  JOIN servico_versao_formularios svf ON svf.servico_versao_id = sol.servico_versao_id
                                     AND svf.etapa_id IS NOT DISTINCT FROM p_etapa
  JOIN formulario_versoes fv ON fv.id = svf.formulario_versao_id
  JOIN secoes s ON s.formulario_versao_id = fv.id
  JOIN campos c ON c.secao_id = s.id
  WHERE sol.id = p_sol AND c.chave = p_chave AND (p_form IS NULL OR fv.formulario_id = p_form);

  IF v_ids IS NULL THEN
    RAISE EXCEPTION 'Não há campo "%" nos formulários deste momento da solicitação.', p_chave;
  ELSIF cardinality(v_ids) > 1 THEN
    RAISE EXCEPTION 'A chave "%" existe em mais de um formulário aqui; informe o formulário (último parâmetro).', p_chave;
  END IF;
  RETURN v_ids[1];
END $$;

-- Quem abriu responde a abertura, enquanto ninguém tiver dado andamento
CREATE FUNCTION responder_abertura(p_user bigint, p_sol bigint, p_chave text, p_valor text, p_form bigint DEFAULT NULL)
RETURNS void LANGUAGE plpgsql AS $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM solicitacoes WHERE id = p_sol AND aberta_por_user_id = p_user) THEN
    RAISE EXCEPTION 'Só quem abriu a solicitação responde o formulário de abertura.';
  END IF;
  IF EXISTS (SELECT 1 FROM tramites WHERE solicitacao_id = p_sol AND saiu_em IS NOT NULL) THEN
    RAISE EXCEPTION 'A solicitação já teve andamento; a abertura não pode mais ser alterada.';
  END IF;
  PERFORM _gravar_resposta(p_sol, _campo_da_solicitacao(p_sol, NULL, p_chave, p_form), NULL, p_valor);
END $$;

-- Quem está lotado no setor da etapa atual responde o formulário da etapa
CREATE FUNCTION responder_etapa(p_user bigint, p_sol bigint, p_chave text, p_valor text, p_form bigint DEFAULT NULL)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE v_etapa bigint; v_setor bigint; v_tramite bigint;
BEGIN
  SELECT s.etapa_atual_id, e.setor_id INTO v_etapa, v_setor
  FROM solicitacoes s LEFT JOIN etapas e ON e.id = s.etapa_atual_id WHERE s.id = p_sol;
  IF v_etapa IS NULL THEN RAISE EXCEPTION 'A solicitação % está encerrada.', p_sol; END IF;
  IF NOT esta_lotado(p_user, v_setor) THEN
    RAISE EXCEPTION 'Usuário % não está lotado no setor da etapa atual.', p_user;
  END IF;
  SELECT id INTO v_tramite FROM tramites WHERE solicitacao_id = p_sol AND saiu_em IS NULL;
  PERFORM _gravar_resposta(p_sol, _campo_da_solicitacao(p_sol, v_etapa, p_chave, p_form), v_tramite, p_valor);
END $$;

-- Cria a notificação e registra os envios pelos canais que a pessoa tem
CREATE FUNCTION _notificar_solicitante(p_sol bigint, p_tramite bigint) RETURNS void LANGUAGE plpgsql AS $$
DECLARE r record; v_msg text; v_not bigint;
BEGIN
  SELECT sol.municipio_id, sol.numero_protocolo, sol.solicitante_pessoa_id, e.nome AS etapa,
         e.mensagem_notificacao, COALESCE(si.rotulo_publico, si.nome) AS situacao, sv.nome AS servico,
         p.email, u.id AS user_id
  INTO r
  FROM tramites t
  JOIN solicitacoes sol ON sol.id = t.solicitacao_id
  JOIN etapas e ON e.id = t.etapa_id
  JOIN situacoes si ON si.id = t.situacao_id
  JOIN servico_versoes svv ON svv.id = sol.servico_versao_id
  JOIN servicos sv ON sv.id = svv.servico_id
  JOIN pessoas p ON p.id = sol.solicitante_pessoa_id
  LEFT JOIN users u ON u.pessoa_id = p.id
  WHERE t.id = p_tramite AND e.notifica_solicitante;
  IF NOT FOUND THEN RETURN; END IF;

  v_msg := replace(replace(replace(replace(r.mensagem_notificacao,
             '{protocolo}', r.numero_protocolo), '{servico}', r.servico), '{etapa}', r.etapa), '{situacao}', r.situacao);

  INSERT INTO notificacoes (municipio_id, solicitacao_id, pessoa_id, tramite_id, mensagem)
  VALUES (r.municipio_id, p_sol, r.solicitante_pessoa_id, p_tramite, v_msg) RETURNING id INTO v_not;

  IF r.user_id IS NOT NULL THEN
    INSERT INTO notificacao_envios (notificacao_id, canal_notificacao_id) VALUES (v_not, _id_slug('canais_notificacao', 'sistema'));
  END IF;
  IF r.email IS NOT NULL THEN
    INSERT INTO notificacao_envios (notificacao_id, canal_notificacao_id, destino) VALUES (v_not, _id_slug('canais_notificacao', 'email'), r.email);
  END IF;
END $$;

-- Quem está lotado no setor da etapa atual escolhe a situação, que move o fluxo
CREATE FUNCTION aplicar_situacao(p_user bigint, p_sol bigint, p_situacao text, p_observacao text DEFAULT NULL)
RETURNS text LANGUAGE plpgsql AS $$
DECLARE v_etapa bigint; v_setor bigint; v_sit situacoes%ROWTYPE; v_faltam text; v_agora timestamptz := clock_timestamp(); v_tramite bigint;
BEGIN
  SELECT s.etapa_atual_id, e.setor_id INTO v_etapa, v_setor
  FROM solicitacoes s LEFT JOIN etapas e ON e.id = s.etapa_atual_id WHERE s.id = p_sol;
  IF v_etapa IS NULL THEN RAISE EXCEPTION 'A solicitação % está encerrada.', p_sol; END IF;

  IF NOT esta_lotado(p_user, v_setor) THEN
    RAISE EXCEPTION 'Usuário % não está lotado no setor da etapa atual.', p_user;
  END IF;

  SELECT * INTO v_sit FROM situacoes WHERE etapa_origem_id = v_etapa AND nome = p_situacao;
  IF v_sit.id IS NULL THEN
    RAISE EXCEPTION 'Situação "%" não existe nesta etapa. Opções: %', p_situacao,
      (SELECT string_agg(nome, ' | ' ORDER BY id) FROM situacoes WHERE etapa_origem_id = v_etapa);
  END IF;

  SELECT string_agg(chave, ', ') INTO v_faltam FROM faltando(p_sol);
  IF v_faltam IS NOT NULL THEN
    RAISE EXCEPTION 'Campos obrigatórios sem resposta: %', v_faltam;
  END IF;

  UPDATE tramites SET situacao_id = v_sit.id, user_id = p_user, saiu_em = v_agora, observacao = p_observacao
  WHERE solicitacao_id = p_sol AND saiu_em IS NULL
  RETURNING id INTO v_tramite;

  PERFORM _notificar_solicitante(p_sol, v_tramite);

  IF v_sit.etapa_destino_id IS NULL THEN
    UPDATE solicitacoes SET etapa_atual_id = NULL, encerrada_em = v_agora WHERE id = p_sol;
    RETURN 'Solicitação encerrada.';
  END IF;

  INSERT INTO tramites (solicitacao_id, etapa_id, entrou_em) VALUES (p_sol, v_sit.etapa_destino_id, v_agora);
  UPDATE solicitacoes SET etapa_atual_id = v_sit.etapa_destino_id WHERE id = p_sol;
  RETURN 'Agora na etapa: ' || (SELECT nome FROM etapas WHERE id = v_sit.etapa_destino_id);
END $$;

