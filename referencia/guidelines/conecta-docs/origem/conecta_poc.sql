LEFT JOIN etapas e ON e.id = sol.etapa_atual_id;

CREATE VIEW ordens_servico_resumo AS
SELECT os.id, os.titulo, COALESCE(sol.numero_protocolo, '(avulsa)') AS origem,
       l.nome || ' — ' || en.logradouro AS local, st.nome AS status,
       to_char(os.iniciada_em, 'DD/MM HH24:MI') AS iniciada, to_char(os.concluida_em, 'DD/MM HH24:MI') AS concluida
FROM ordens_servico os
JOIN enderecos en ON en.id = os.endereco_id
JOIN localidades l ON l.id = en.localidade_id
JOIN status_os st ON st.id = os.status_os_id
LEFT JOIN solicitacoes sol ON sol.id = os.solicitacao_id;
