$$;

-- Autocadastro (portal e app). p_canal escolhe por onde vai o código quando
-- a pessoa já existe e tem e-mail E telefone ('email' ou 'sms').
-- Devolve o que o BFF responderia: criado | confirmacao_pendente.
CREATE FUNCTION cadastrar(p_cpf text, p_nome text, p_senha text,
                          p_email text DEFAULT NULL, p_telefone text DEFAULT NULL, p_canal text DEFAULT NULL)
RETURNS jsonb LANGUAGE plpgsql AS $$
DECLARE pe pessoas%ROWTYPE; v_canal text; v_destino text; v_codigo text; v_conf bigint;
BEGIN
  IF COALESCE(btrim(p_senha), '') = '' THEN RAISE EXCEPTION 'Escolha uma senha.'; END IF;
  SELECT * INTO pe FROM pessoas WHERE cpf = p_cpf;

  IF pe.id IS NULL THEN
    INSERT INTO pessoas (cpf, nome, email, telefone) VALUES (p_cpf, p_nome, p_email, p_telefone) RETURNING * INTO pe;
    INSERT INTO users (pessoa_id, password) VALUES (pe.id, md5(p_senha));
    RETURN jsonb_build_object('status', 'criado', 'pessoa_id', pe.id);
  END IF;

  IF EXISTS (SELECT 1 FROM users WHERE pessoa_id = pe.id) THEN
    RAISE EXCEPTION 'cpf_ja_cadastrado: esse CPF já tem login.';
  END IF;

  -- pessoa sem login: o código vai SÓ para o contato já cadastrado
  IF pe.email IS NULL AND pe.telefone IS NULL THEN
    RAISE EXCEPTION 'confirmacao_indisponivel: não há e-mail nem telefone cadastrados; procure o atendimento.';
  END IF;
  v_canal := COALESCE(p_canal, CASE WHEN pe.email IS NOT NULL AND pe.telefone IS NULL THEN 'email'
                                    WHEN pe.telefone IS NOT NULL AND pe.email IS NULL THEN 'sms' END);
  IF v_canal IS NULL THEN RAISE EXCEPTION 'escolha_canal: a pessoa tem e-mail e telefone; informe p_canal (email ou sms).'; END IF;
  v_destino := CASE v_canal WHEN 'email' THEN pe.email WHEN 'sms' THEN pe.telefone END;
  IF v_destino IS NULL THEN RAISE EXCEPTION 'A pessoa não tem % cadastrado.', v_canal; END IF;

  v_codigo := lpad((floor(random() * 1000000))::int::text, 6, '0');
  INSERT INTO confirmacoes_cadastro (pessoa_id, canal_confirmacao_id, destino, codigo_hash, senha_hash, expira_em)
  VALUES (pe.id, _id_slug('canais_confirmacao', v_canal), v_destino, md5(v_codigo), md5(p_senha), clock_timestamp() + interval '10 minutes')
  RETURNING id INTO v_conf;
  PERFORM _enviar_mock(v_canal, v_destino, 'Conecta+: seu código de confirmação é ' || v_codigo || '. Vale por 10 minutos.');

  RETURN jsonb_build_object('status', 'confirmacao_pendente', 'confirmacao_id', v_conf,
                            'canal', v_canal, 'destino', _mascarar(v_canal, v_destino));
END $$;

CREATE FUNCTION confirmar_cadastro(p_confirmacao bigint, p_codigo text) RETURNS jsonb LANGUAGE plpgsql AS $$
DECLARE c confirmacoes_cadastro%ROWTYPE; v_user bigint;
BEGIN
  SELECT * INTO c FROM confirmacoes_cadastro WHERE id = p_confirmacao FOR UPDATE;
  IF c.id IS NULL THEN RAISE EXCEPTION 'Confirmação % não existe.', p_confirmacao; END IF;
  IF c.confirmada_em IS NOT NULL THEN RAISE EXCEPTION 'Essa confirmação já foi usada.'; END IF;
  IF c.expira_em < clock_timestamp() THEN RAISE EXCEPTION 'codigo_expirado: peça um novo código.'; END IF;
  IF c.tentativas >= 5 THEN RAISE EXCEPTION 'tentativas_esgotadas: peça um novo código.'; END IF;
  IF md5(p_codigo) <> c.codigo_hash THEN
    UPDATE confirmacoes_cadastro SET tentativas = tentativas + 1 WHERE id = c.id;
    RETURN jsonb_build_object('status', 'codigo_invalido', 'restam', 4 - c.tentativas);
  END IF;
  IF EXISTS (SELECT 1 FROM users WHERE pessoa_id = c.pessoa_id) THEN RAISE EXCEPTION 'cpf_ja_cadastrado'; END IF;

  INSERT INTO users (pessoa_id, password) VALUES (c.pessoa_id, c.senha_hash) RETURNING id INTO v_user;
  UPDATE confirmacoes_cadastro SET confirmada_em = clock_timestamp() WHERE id = c.id;
  RETURN jsonb_build_object('status', 'criado', 'user_id', v_user);
END $$;

