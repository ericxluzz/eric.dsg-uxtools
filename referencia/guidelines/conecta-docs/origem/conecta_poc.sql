-- A partir de uma solicitação (copia o endereço) ou avulsa (informa o local)
CREATE FUNCTION criar_os(p_user bigint, p_secretaria bigint, p_titulo text, p_descricao text,
                         p_solicitacao bigint DEFAULT NULL,
                         p_localidade bigint DEFAULT NULL, p_logradouro text DEFAULT NULL,
                         p_responsavel bigint DEFAULT NULL)
RETURNS bigint LANGUAGE plpgsql AS $$
DECLARE v_mun bigint; v_end bigint; v bigint;
BEGIN
  SELECT municipio_id INTO v_mun FROM secretarias WHERE id = p_secretaria;
  PERFORM _exigir_permissao(p_user, v_mun, 'criar_os');

  IF p_solicitacao IS NOT NULL THEN
    INSERT INTO enderecos (municipio_id, localidade_id, logradouro, referencia, latitude, longitude)
    SELECT e.municipio_id, e.localidade_id, e.logradouro, e.referencia, e.latitude, e.longitude
    FROM solicitacoes s JOIN enderecos e ON e.id = s.endereco_id
    WHERE s.id = p_solicitacao AND s.municipio_id = v_mun
    RETURNING id INTO v_end;
    IF v_end IS NULL THEN RAISE EXCEPTION 'Solicitação % não existe neste município.', p_solicitacao; END IF;
  ELSE
    IF p_localidade IS NULL OR p_logradouro IS NULL THEN
      RAISE EXCEPTION 'OS avulsa precisa de localidade e logradouro.';
    END IF;
    INSERT INTO enderecos (municipio_id, localidade_id, logradouro) VALUES (v_mun, p_localidade, p_logradouro)
    RETURNING id INTO v_end;
  END IF;

  INSERT INTO ordens_servico (municipio_id, secretaria_id, solicitacao_id, endereco_id, titulo, descricao,
                              status_os_id, responsavel_id)
  VALUES (v_mun, p_secretaria, p_solicitacao, v_end, p_titulo, p_descricao, _id_slug('status_os', 'planejada'), p_responsavel)
  RETURNING id INTO v;
  RETURN v;
END $$;

CREATE FUNCTION mudar_status_os(p_os bigint, p_status text) RETURNS void LANGUAGE plpgsql AS $$
DECLARE v_atual_final boolean;
BEGIN
  SELECT st.final INTO v_atual_final FROM ordens_servico os JOIN status_os st ON st.id = os.status_os_id WHERE os.id = p_os;
  IF v_atual_final THEN RAISE EXCEPTION 'A OS % já está num status final.', p_os; END IF;
  UPDATE ordens_servico SET
    status_os_id = _id_slug('status_os', p_status),
    iniciada_em  = CASE WHEN p_status = 'em_execucao' THEN COALESCE(iniciada_em, clock_timestamp()) ELSE iniciada_em END,
    concluida_em = CASE WHEN p_status = 'concluida'   THEN clock_timestamp() ELSE concluida_em END
  WHERE id = p_os;
END $$;

