-- chave única dentro da versão do formulário (atravessa seções)
CREATE FUNCTION campos_chave_unica() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF EXISTS (
    SELECT 1
    FROM campos c
    JOIN secoes s  ON s.id = c.secao_id
    JOIN secoes sn ON sn.id = NEW.secao_id
    WHERE s.formulario_versao_id = sn.formulario_versao_id
      AND c.chave = NEW.chave
      AND c.id <> NEW.id
  ) THEN
    RAISE EXCEPTION 'A chave "%" já existe nesta versão do formulário.', NEW.chave;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_campos_chave_unica BEFORE INSERT OR UPDATE ON campos
  FOR EACH ROW EXECUTE FUNCTION campos_chave_unica();

