-- Copia seções, campos, opções, validações e condições de uma versão para outra
CREATE FUNCTION _copiar_formulario_versao(p_origem bigint, p_destino bigint) RETURNS void LANGUAGE plpgsql AS $$
DECLARE
  ms jsonb := '{}'; mc jsonb := '{}'; mg jsonb := '{}';
  r record; v bigint;
BEGIN
  FOR r IN SELECT * FROM secoes WHERE formulario_versao_id = p_origem ORDER BY ordem LOOP
    INSERT INTO secoes (formulario_versao_id, titulo, ordem) VALUES (p_destino, r.titulo, r.ordem) RETURNING id INTO v;
    ms := ms || jsonb_build_object(r.id::text, v);
  END LOOP;

  FOR r IN SELECT c.* FROM campos c JOIN secoes s ON s.id = c.secao_id WHERE s.formulario_versao_id = p_origem LOOP
    INSERT INTO campos (secao_id, chave, tipo_campo_id, rotulo, ajuda, obrigatorio, ordem)
    VALUES ((ms ->> r.secao_id::text)::bigint, r.chave, r.tipo_campo_id, r.rotulo, r.ajuda, r.obrigatorio, r.ordem)
    RETURNING id INTO v;
    mc := mc || jsonb_build_object(r.id::text, v);
    INSERT INTO campo_opcoes (campo_id, rotulo, valor, ordem) SELECT v, rotulo, valor, ordem FROM campo_opcoes WHERE campo_id = r.id;
    INSERT INTO campo_validacoes (campo_id, tipo_validacao_id, valor) SELECT v, tipo_validacao_id, valor FROM campo_validacoes WHERE campo_id = r.id;
  END LOOP;

  FOR r IN
    WITH RECURSIVE g AS (
      SELECT cg.*, 0 AS nivel FROM condicao_grupos cg
      WHERE cg.parent_grupo_id IS NULL
        AND (cg.secao_id IN (SELECT id FROM secoes WHERE formulario_versao_id = p_origem)
          OR cg.campo_id IN (SELECT c.id FROM campos c JOIN secoes s ON s.id = c.secao_id WHERE s.formulario_versao_id = p_origem))
      UNION ALL
      SELECT f.*, g.nivel + 1 FROM condicao_grupos f JOIN g ON f.parent_grupo_id = g.id
    )
    SELECT * FROM g ORDER BY nivel, id
  LOOP
    INSERT INTO condicao_grupos (parent_grupo_id, campo_id, secao_id, logica)
    VALUES ((mg ->> r.parent_grupo_id::text)::bigint, (mc ->> r.campo_id::text)::bigint,
            (ms ->> r.secao_id::text)::bigint, r.logica)
    RETURNING id INTO v;
    mg := mg || jsonb_build_object(r.id::text, v);
    INSERT INTO condicoes (grupo_id, operador_id, gatilho_formulario_id, gatilho_chave, valor)
    SELECT v, operador_id, gatilho_formulario_id, gatilho_chave, valor FROM condicoes WHERE grupo_id = r.id;
  END LOOP;
END $$;

-- Versão em edição: o rascunho, ou um rascunho novo copiado da versão publicada
CREATE FUNCTION formulario_em_edicao(p_form bigint) RETURNS bigint LANGUAGE plpgsql AS $$
DECLARE v bigint; v_atual bigint;
BEGIN
  SELECT id INTO v FROM formulario_versoes WHERE formulario_id = p_form AND status = 'rascunho';
  IF v IS NOT NULL THEN RETURN v; END IF;

  SELECT versao_atual_id INTO v_atual FROM formularios WHERE id = p_form;
  IF v_atual IS NULL THEN RAISE EXCEPTION 'Formulário % não existe.', p_form; END IF;

  INSERT INTO formulario_versoes (formulario_id, numero, status)
  VALUES (p_form, (SELECT max(numero) + 1 FROM formulario_versoes WHERE formulario_id = p_form), 'rascunho')
  RETURNING id INTO v;
  PERFORM _copiar_formulario_versao(v_atual, v);
  RAISE NOTICE 'Rascunho novo do formulário % criado a partir da versão publicada.', p_form;
  RETURN v;
END $$;

CREATE FUNCTION _secao_em_edicao(p_form bigint, p_titulo text) RETURNS bigint LANGUAGE plpgsql AS $$
DECLARE v bigint; v_versao bigint := formulario_em_edicao(p_form);
BEGIN
  SELECT id INTO v FROM secoes WHERE formulario_versao_id = v_versao AND titulo = p_titulo;
  IF v IS NULL THEN
    RAISE EXCEPTION 'Seção "%" não existe no formulário %. Seções: %', p_titulo, p_form,
      (SELECT string_agg(titulo, ', ' ORDER BY ordem) FROM secoes WHERE formulario_versao_id = v_versao);
  END IF;
  RETURN v;
END $$;

CREATE FUNCTION _campo_em_edicao(p_form bigint, p_chave text) RETURNS bigint LANGUAGE plpgsql AS $$
DECLARE v bigint; v_versao bigint := formulario_em_edicao(p_form);
BEGIN
  SELECT c.id INTO v FROM campos c JOIN secoes s ON s.id = c.secao_id
  WHERE s.formulario_versao_id = v_versao AND c.chave = p_chave;
  IF v IS NULL THEN
    RAISE EXCEPTION 'Campo "%" não existe no formulário %.', p_chave, p_form;
  END IF;
  RETURN v;
END $$;

CREATE FUNCTION adicionar_secao(p_form bigint, p_titulo text) RETURNS bigint LANGUAGE plpgsql AS $$
DECLARE v_versao bigint := formulario_em_edicao(p_form); v bigint;
BEGIN
  IF EXISTS (SELECT 1 FROM secoes WHERE formulario_versao_id = v_versao AND titulo = p_titulo) THEN
    RAISE EXCEPTION 'Já existe a seção "%" neste formulário.', p_titulo;
  END IF;
  INSERT INTO secoes (formulario_versao_id, titulo, ordem)
  VALUES (v_versao, p_titulo, COALESCE((SELECT max(ordem) FROM secoes WHERE formulario_versao_id = v_versao), 0) + 1)
  RETURNING id INTO v;
  RETURN v;
END $$;

CREATE FUNCTION adicionar_campo(p_form bigint, p_secao text, p_chave text, p_tipo text, p_rotulo text,
                                p_obrigatorio boolean DEFAULT false, p_ajuda text DEFAULT NULL)
RETURNS bigint LANGUAGE plpgsql AS $$
DECLARE v_secao bigint := _secao_em_edicao(p_form, p_secao); v bigint;
BEGIN
  INSERT INTO campos (secao_id, chave, tipo_campo_id, rotulo, ajuda, obrigatorio, ordem)
  VALUES (v_secao, p_chave, _id_slug('tipos_campo', p_tipo), p_rotulo, p_ajuda, p_obrigatorio,
          COALESCE((SELECT max(ordem) FROM campos WHERE secao_id = v_secao), 0) + 1)
  RETURNING id INTO v;
  RETURN v;
END $$;

CREATE FUNCTION remover_campo(p_form bigint, p_chave text) RETURNS void LANGUAGE plpgsql AS $$
DECLARE v_campo bigint := _campo_em_edicao(p_form, p_chave);
BEGIN
  DELETE FROM condicoes WHERE grupo_id IN (
    WITH RECURSIVE g AS (SELECT id FROM condicao_grupos WHERE campo_id = v_campo
                         UNION ALL SELECT f.id FROM condicao_grupos f JOIN g ON f.parent_grupo_id = g.id)
    SELECT id FROM g);
  DELETE FROM condicao_grupos WHERE id IN (
    WITH RECURSIVE g AS (SELECT id, 0 AS n FROM condicao_grupos WHERE campo_id = v_campo
                         UNION ALL SELECT f.id, g.n + 1 FROM condicao_grupos f JOIN g ON f.parent_grupo_id = g.id)
    SELECT id FROM g);
  DELETE FROM campo_opcoes WHERE campo_id = v_campo;
  DELETE FROM campo_validacoes WHERE campo_id = v_campo;
  DELETE FROM campos WHERE id = v_campo;
END $$;

CREATE FUNCTION adicionar_opcao(p_form bigint, p_chave text, p_rotulo text, p_valor text) RETURNS bigint LANGUAGE plpgsql AS $$
DECLARE v_campo bigint := _campo_em_edicao(p_form, p_chave); v_tipo text; v bigint;
BEGIN
  SELECT tc.slug INTO v_tipo FROM campos c JOIN tipos_campo tc ON tc.id = c.tipo_campo_id WHERE c.id = v_campo;
  IF v_tipo NOT IN ('selecao', 'multipla_escolha') THEN
    RAISE EXCEPTION 'O campo "%" é do tipo %, que não tem opções.', p_chave, v_tipo;
  END IF;
  INSERT INTO campo_opcoes (campo_id, rotulo, valor, ordem)
  VALUES (v_campo, p_rotulo, p_valor, COALESCE((SELECT max(ordem) FROM campo_opcoes WHERE campo_id = v_campo), 0) + 1)
  RETURNING id INTO v;
  RETURN v;
END $$;

CREATE FUNCTION adicionar_validacao(p_form bigint, p_chave text, p_tipo_validacao text, p_valor text) RETURNS bigint LANGUAGE sql AS $$
  INSERT INTO campo_validacoes (campo_id, tipo_validacao_id, valor)
  VALUES (_campo_em_edicao(p_form, p_chave), _id_slug('tipos_validacao', p_tipo_validacao), p_valor)
  RETURNING id
$$;

-- Condições: cria o grupo raiz (alvo = campo ou seção), subgrupos e condições
CREATE FUNCTION condicao_no_campo(p_form bigint, p_chave text, p_logica text DEFAULT 'E') RETURNS bigint LANGUAGE sql AS $$
  INSERT INTO condicao_grupos (campo_id, logica) VALUES (_campo_em_edicao(p_form, p_chave), p_logica) RETURNING id
$$;

CREATE FUNCTION condicao_na_secao(p_form bigint, p_secao text, p_logica text DEFAULT 'E') RETURNS bigint LANGUAGE sql AS $$
  INSERT INTO condicao_grupos (secao_id, logica) VALUES (_secao_em_edicao(p_form, p_secao), p_logica) RETURNING id
$$;

CREATE FUNCTION subgrupo(p_grupo bigint, p_logica text) RETURNS bigint LANGUAGE sql AS $$
  INSERT INTO condicao_grupos (parent_grupo_id, logica) VALUES (p_grupo, p_logica) RETURNING id
$$;

CREATE FUNCTION adicionar_condicao(p_grupo bigint, p_gatilho_form bigint, p_gatilho_chave text,
                                   p_operador text, p_valor text DEFAULT NULL)
RETURNS bigint LANGUAGE plpgsql AS $$
DECLARE v bigint;
BEGIN
  IF NOT EXISTS (SELECT 1 FROM campos c JOIN secoes s ON s.id = c.secao_id
                 JOIN formulario_versoes fv ON fv.id = s.formulario_versao_id
                 WHERE fv.formulario_id = p_gatilho_form AND c.chave = p_gatilho_chave) THEN
    RAISE EXCEPTION 'O formulário % não tem campo com a chave "%".', p_gatilho_form, p_gatilho_chave;
  END IF;
  INSERT INTO condicoes (grupo_id, operador_id, gatilho_formulario_id, gatilho_chave, valor)
  VALUES (p_grupo, _id_slug('operadores', p_operador), p_gatilho_form, p_gatilho_chave, p_valor)
  RETURNING id INTO v;
  RETURN v;
END $$;

