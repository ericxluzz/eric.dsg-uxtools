           WHERE s.municipio_id = p_municipio AND s.ativo
             AND NOT EXISTS (SELECT 1 FROM servicos_por_canal v WHERE v.servico_id = s.id)
  LOOP
    RAISE NOTICE 'AVISO: o serviço "%" ficou indisponível em todos os canais.', r.nome;
  END LOOP;
END $$;

